"""Postgres dialect: the hosted, shared database every Lineage server and CI job connects to.
Everything Lineage stores lives in one schema (default `lineage`) beside the client's own data.

Built for a database across the network: TLS by default for remote hosts, a connection pool that
detects connections dropped by failovers or idle timeouts, settings applied once per connection
instead of per query, and batched writes. Keywords: tsvector + GIN. Vectors: pgvector + HNSW.
"""

from __future__ import annotations

import logging
import os
import re
import threading
import time
from typing import Any, Sequence

from psycopg.conninfo import conninfo_to_dict, make_conninfo
from psycopg.errors import UndefinedColumn
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool, PoolTimeout

from lineage.store.base import Scope
from lineage.store.sql import COMMON_DDL, SqlStore, scope_clause
from lineage.text import tokens

log = logging.getLogger(__name__)

DDL = COMMON_DDL.format(id="bigint generated by default as identity primary key", ref="bigint") + """
create table if not exists chunks(
    id bigint generated by default as identity primary key,
    file_id bigint not null references files(id) on delete cascade,
    symbol_id bigint references symbols(id) on delete cascade,
    system_id text not null, start_line integer not null, end_line integer not null,
    tsv tsvector not null);
create index if not exists chunks_file on chunks(file_id);
create index if not exists chunks_system on chunks(system_id);
create index if not exists chunks_tsv on chunks using gin(tsv);
"""

VECTOR_INDEX = "create index if not exists chunks_embedding on chunks using hnsw (embedding vector_cosine_ops)"
SCHEMA_RE = re.compile(r"^[a-z_][a-z0-9_]{0,62}$")
EF_SEARCH = 200  # HNSW candidate list; high enough that per-project filtering still fills top-k
LOCAL_HOSTS = ("", "localhost", "127.0.0.1", "::1")
WEAK_SSLMODES = ("disable", "allow", "prefer")


def secure_conninfo(url: str) -> str:
    """Require TLS for any non-local host unless the URL (or PGSSLMODE) says otherwise."""
    params = conninfo_to_dict(url)
    host = str(params.get("host", ""))
    remote = host not in LOCAL_HOSTS and not host.startswith("/")
    if remote and "sslmode" not in params and "PGSSLMODE" not in os.environ:
        params["sslmode"] = "require"
    elif remote and params.get("sslmode") in WEAK_SSLMODES:
        log.warning("database connection to %s allows plain text (sslmode=%s)", host, params["sslmode"])
    return make_conninfo(**params)


def describe(url: str) -> str:
    """The connection without its password, for logs and diagnostics."""
    p = conninfo_to_dict(url)
    return (f"postgresql://{p.get('user', '')}@{p.get('host', 'localhost')}:{p.get('port', 5432)}"
            f"/{p.get('dbname', '')} sslmode={p.get('sslmode', os.environ.get('PGSSLMODE', 'default'))}")


IDLE_CHECK_S = 30


def _mark_used(conn) -> None:
    conn.info_lineage_returned = time.monotonic()


def _check_if_idle(conn) -> None:
    """Ping only connections that sat idle (the ones a failover or idle timeout may have killed):
    pinging every checkout would add a network round trip to every request."""
    if time.monotonic() - getattr(conn, "info_lineage_returned", 0.0) > IDLE_CHECK_S:
        ConnectionPool.check_connection(conn)


class _Pool:
    """One per (database, schema) per process: the pool plus facts learned at startup."""

    def __init__(self, conninfo: str, schema: str, size: int, statement_timeout_s: int):
        self.schema, self.statement_timeout_s = schema, statement_timeout_s
        self.pgvector: tuple[int, ...] = ()

        def configure(conn) -> None:
            # Session settings once per connection, not per query: each would be a network round trip.
            row = conn.execute("select n.nspname, e.extversion from pg_extension e join pg_namespace n"
                               " on n.oid = e.extnamespace where e.extname = 'vector'").fetchone()
            ext_schema = row["nspname"] if row else "public"
            conn.execute(f'set search_path to "{schema}", "{ext_schema}", public')
            conn.execute(f"set statement_timeout = '{statement_timeout_s}s'")
            conn.execute(f"set hnsw.ef_search = {EF_SEARCH}")
            if row and _version(row["extversion"]) >= (0, 8):  # keeps filtered queries from coming back short
                conn.execute("set hnsw.iterative_scan = relaxed_order")

        self.pool = ConnectionPool(
            conninfo, min_size=1, max_size=size, open=True, configure=configure,
            check=_check_if_idle, reset=_mark_used,
            max_idle=300, max_lifetime=3600, name=f"lineage-{schema}",
            # prepare_threshold=None: no server-side prepared statements, so poolers like PgBouncer work.
            kwargs={"autocommit": True, "row_factory": dict_row, "prepare_threshold": None})
        try:
            self._initialize()
        except PoolTimeout as e:
            self.pool.close()
            raise RuntimeError(f"cannot reach the database at {describe(conninfo)}: check that it is running, "
                               "the host/port, credentials and firewall (`lineage db check` retries it)") from e

    def _initialize(self) -> None:
        """Create or migrate the schema once per process; an advisory lock serialises servers."""
        with self.pool.connection() as conn, conn.transaction():
            conn.execute("select pg_advisory_xact_lock(hashtext(%s))", (f"lineage:{self.schema}",))
            # Least privilege: a DBA may pre-create the schema and grant it; then no CREATE on the database is needed.
            if conn.execute("select 1 as x from pg_namespace where nspname = %s", (self.schema,)).fetchone() is None:
                conn.execute(f'create schema "{self.schema}"')
            if conn.execute("select 1 as x from pg_extension where extname = 'vector'").fetchone() is None:
                with conn.transaction():  # savepoint: a privilege error must not abort the outer transaction
                    try:
                        conn.execute("create extension if not exists vector schema public")
                    except Exception as e:
                        raise RuntimeError("pgvector is not installed in this database. Ask the DBA to run "
                                           "`CREATE EXTENSION vector;` once, then restart Lineage.") from e
            self.pgvector = _version(conn.execute(
                "select extversion from pg_extension where extname = 'vector'").fetchone()["extversion"])
            conn.execute(DDL)
            store = PostgresStore.__new__(PostgresStore)
            store.db = conn
            store._migrate()
            if store._meta("dim"):  # self-heal: a crashed bulk load may have left the vector index dropped
                conn.execute(VECTOR_INDEX)


_pools: dict[tuple[str, str], _Pool] = {}
_pools_lock = threading.Lock()


def _version(text: str) -> tuple[int, ...]:
    return tuple(int(p) for p in re.findall(r"\d+", text)[:3])


def _vector(values: list[float]) -> str:
    return "[" + ",".join(f"{v:.7g}" for v in values) + "]"


class PostgresStore(SqlStore):
    AGG = "string_agg"

    def __init__(self, url: str, schema: str = "lineage", pool_size: int = 10, statement_timeout_s: int = 60):
        if not SCHEMA_RE.fullmatch(schema):
            raise ValueError("db_schema must be a lowercase SQL identifier")
        conninfo = secure_conninfo(url)
        with _pools_lock:
            if (conninfo, schema) not in _pools:
                _pools[(conninfo, schema)] = _Pool(conninfo, schema, pool_size, statement_timeout_s)
            self._p = _pools[(conninfo, schema)]
        self._lease = self._p.pool.connection()
        self.db = self._lease.__enter__()
        self._bulk = False

    def __enter__(self) -> "PostgresStore":
        return self

    def __exit__(self, *exc) -> None:
        if self._bulk:  # the pooled connection goes back with normal settings
            try:
                self._execute("reset synchronous_commit")
                self._execute(f"set statement_timeout = '{self._p.statement_timeout_s}s'")
            except Exception:  # a broken connection: the pool discards it anyway
                pass
        self._lease.__exit__(*exc)

    def _server_info(self) -> dict:
        timings = []
        for _ in range(5):
            t = time.perf_counter()
            self._execute("select 1")
            timings.append((time.perf_counter() - t) * 1000)
        ssl = self._one("select ssl, version as tls from pg_stat_ssl where pid = pg_backend_pid()")
        return {
            "database": "postgres",
            "server": self._one("select current_setting('server_version') as v")["v"],
            "connection": describe(self.db.info.dsn),
            "tls": ssl["tls"] if ssl and ssl["ssl"] else None,
            "schema": self._p.schema,
            "pgvector": ".".join(map(str, self._p.pgvector)),
            "round_trip_ms": round(sorted(timings)[2], 1),
            "pool_size": self._p.pool.max_size,
        }

    def _execute(self, sql: str, params: Sequence[Any] = ()) -> Any:
        return self.db.execute(sql.replace("?", "%s"), params)

    def _executemany(self, sql: str, rows: list[Sequence[Any]]) -> None:
        with self.db.cursor() as cur:
            cur.executemany(sql.replace("?", "%s"), rows)  # pipelined: one round trip per batch, not per row

    def _tx(self):
        return self.db.transaction()

    def _insert_ids(self, table: str, cols: Sequence[str], rows: list[Sequence[Any]]) -> list[int]:
        if len(rows) <= 1:
            return super()._insert_ids(table, cols, rows)
        # Reserve ids in one round trip, then one pipelined batch insert.
        ids = [r["id"] for r in self._all(
            "select nextval(pg_get_serial_sequence(?, 'id')) as id from generate_series(1, ?)",
            (f'"{self._p.schema}".{table}', len(rows)))]
        self._executemany(f"insert into {table}(id, {', '.join(cols)}) values ({', '.join('?' * (len(cols) + 1))})",
                          [(i, *r) for i, r in zip(ids, rows)])
        return ids

    def _delete(self, system_id: str, paths: Sequence[str]) -> None:
        if paths:  # one statement for the whole batch; chunks/symbols/edges follow by cascade
            self._execute("delete from files where system_id = ? and path = any(?)", (system_id, list(paths)))

    def begin_bulk(self, large: bool) -> None:
        self._bulk, self._large_load = True, large
        # Commits stop waiting on fsync for this session only. A crash can lose the last batch's
        # rows, never corrupt anything; the next run re-indexes them by hash. Index builds may
        # legitimately run for minutes, so the per-statement safety timeout is lifted too.
        self._execute("set synchronous_commit to off")
        self._execute("set statement_timeout = 0")
        if large:
            # Maintaining HNSW per inserted row is ~1.3 ms/chunk; one build afterwards is ~5x faster
            # overall. Meanwhile vector search stays correct via an exact scan, just slower.
            self._execute("drop index if exists chunks_embedding")

    def end_bulk(self) -> None:
        self._execute("set maintenance_work_mem = '512MB'")
        self._execute(VECTOR_INDEX)
        self._execute("reset maintenance_work_mem")
        if self._large_load:
            # Without fresh statistics the planner misjudges the new rows: searches measured 9x slower.
            for table in ("files", "symbols", "edges", "chunks"):
                self._execute(f"analyze {table}")

    def _create_vector_index(self, dim: int) -> None:
        self._execute(f"alter table chunks add column if not exists embedding vector({dim})")
        self._execute(VECTOR_INDEX)

    def _insert_chunks(self, system_id: str, rows: list[tuple]) -> None:
        self._executemany(
            "insert into chunks(file_id, symbol_id, system_id, start_line, end_line, tsv, embedding)"
            " values (?, ?, ?, ?, ?, to_tsvector('simple', ?), ?::vector)",
            [(fid, sid, system_id, start, end, " ".join(tokens(text)), _vector(vec))
             for fid, sid, start, end, text, vec in rows])

    def keyword_search(self, terms: Sequence[str], systems: Scope, limit: int) -> list[tuple[int, float]]:
        terms = [t for t in terms if t.isalnum()]
        if not terms:
            return []
        clause, params = scope_clause("c.system_id", systems)
        rows = self._all(
            "select c.id, ts_rank(c.tsv, q) as score from chunks c, to_tsquery('simple', ?) q"
            f" where c.tsv @@ q{clause} order by score desc limit ?", [" | ".join(terms), *params, limit])
        return [(r["id"], r["score"]) for r in rows]

    def vector_search(self, vector: list[float], systems: Scope, limit: int) -> list[tuple[int, float]]:
        clause, params = scope_clause("system_id", systems)
        q = _vector(vector)
        try:
            rows = self._all(
                f"select id, embedding <=> ?::vector as distance from chunks where embedding is not null{clause}"
                " order by embedding <=> ?::vector limit ?", [q, *params, q, limit])
        except UndefinedColumn:  # nothing indexed yet: the embedding column does not exist
            return []
        return [(r["id"], r["distance"]) for r in rows]
